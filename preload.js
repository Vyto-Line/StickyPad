const { contextBridge, ipcRenderer } = require('electron');
const call = c => (...a) => ipcRenderer.invoke(c, ...a);
contextBridge.exposeInMainWorld('api', {
  get: call('note:get'), remind: call('note:remind'), aiWarmup: call('ai:warmup'), noteExport: call('note:export'), histList: call('hist:list'), histRestore: call('hist:restore'), update: call('note:update'), pin: call('note:pin'), roll: call('note:roll'),
  newNote: call('note:new'), close: call('note:close'), remove: call('note:delete'),
  lock: call('note:lock'), unlock: call('note:unlock'), relock: call('note:relock'), removeLock: call('note:removeLock'),
  saveImage: call('img:save'),
  info: call('app:info'), setStartup: call('app:startup'), setHideTaskbar: call('app:hideTaskbar'), setSnap: call('app:snap'),
  openTrash: call('trash:open'), openAll: call('all:open'), tidy: call('all:tidy'),
  allList: call('all:list'), allShow: call('all:show'), allContext: call('all:context'), allNew: call('all:new'), allOpenGroup: call('all:openGroup'),
  grpNew: call('grp:new'), grpUpdate: call('grp:update'), grpDelete: call('grp:delete'), grpMove: call('grp:move'),
  trashRestore: call('trash:restore'), trashPurge: call('trash:purge'), trashEmpty: call('trash:empty'),
  prefs: call('app:prefs'),
  openSettings: call('settings:open'), settingsGet: call('settings:get'), settingsSet: call('settings:set'), settingsAction: call('settings:action'),
  onSettingsSection: cb => ipcRenderer.on('settings:section', (e, s) => cb(s)),
  themeSet: call('theme:set'), themeApplyAll: call('theme:applyAll'),
  onReload: cb => ipcRenderer.on('note:reload', () => cb()),
  onStyle: cb => ipcRenderer.on('note:style', (e, st) => cb(st)),
  openChat: call('chat:open'), chatClose: call('chat:close'), chatLoad: call('chat:load'), chatSave: call('chat:save'),
  chatNotes: call('chat:notes'), chatSend: call('chat:send'), chatStop: call('chat:stop'), chatSaveAsNote: call('chat:saveAsNote'),
  onChatEvent: cb => ipcRenderer.on('chat:event', (e, m) => cb(m)),
  onChatAttach: cb => ipcRenderer.on('chat:attach', (e, id) => cb(id)),
  aiEdit: call('ai:edit'), aiEditStop: call('ai:editStop'), onAiEvent: cb => ipcRenderer.on('ai:event', (e, m) => cb(m)),
  ollamaStatus: call('ollama:status'), ollamaStart: call('ollama:start'), ollamaPull: call('ollama:pull'), ollamaCancel: call('ollama:cancel'), ollamaInstall: call('ollama:install'),
  onOllamaEvent: cb => ipcRenderer.on('ollama:event', (e, m) => cb(m)),
  updateCheck: call('update:check'), updateState: call('update:state'), updateInstall: call('update:install'),
  onUpdateEvent: cb => ipcRenderer.on('update:event', (e, m) => cb(m)),
  openLink: call('app:openLink'), linkMenu: call('app:linkMenu'), onKeys: cb => ipcRenderer.on('keys:changed', (e, m) => cb(m)),
  aiGet: call('ai:get'), aiSet: call('ai:set'), aiRun: call('ai:run'),
  onAllTab: cb => ipcRenderer.on('all:tab', (e, t) => cb(t)),
  onAllChanged: cb => ipcRenderer.on('all:changed', () => cb()),
});
