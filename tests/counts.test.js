const assert = require('assert'), C = require('../counts');
assert.strictEqual(C.target('How many times does the word "alpha" appear in this note?'), 'alpha');
assert.strictEqual(C.target('how many times does alpha appear'), 'alpha');
assert.strictEqual(C.target('How many times is the word beta used?'), 'beta');
assert.strictEqual(C.target('πόσες φορές υπάρχει η λέξη καλημέρα;'), 'καλημέρα');
assert.strictEqual(C.target('Πόσες φορές αναφέρεται «Αθήνα» στο σημείωμα;'), 'Αθήνα');
assert.strictEqual(C.target('Summarise this note'), '', 'not a counting question');
assert.strictEqual(C.target('How many items are on my list?'), '', 'no word to count');
assert.deepStrictEqual(C.count('Alpha alpha ALPHA alphabet', 'alpha'), { any: 4, whole: 3 });
assert.deepStrictEqual(C.count('Καλημέρα καλημερα ΚΑΛΗΜΈΡΑ', 'καλημέρα'), { any: 3, whole: 3 }, 'capitals and accents do not matter');
assert.deepStrictEqual(C.count('aaaa', 'aa'), { any: 2, whole: 0 }, 'no overlapping');
assert.deepStrictEqual(C.count('abc', ''), { any: 0, whole: 0 });
assert.deepStrictEqual(C.count('a.b (a)', 'a'), { any: 2, whole: 2 }, 'punctuation ends a word; regex characters are safe');
assert.doesNotThrow(() => C.count('x', '.*+?^${}()|[]\\'));
const big = Array.from({ length: 46511 }, () => 'alpha').join(' ') + ' beta';
assert.strictEqual(C.count(big, 'alpha').any, 46511);
const f = C.facts('How many times does alpha appear?', [{ title: 'Big', text: big }]);
assert.ok(f.includes('46,511 times') && f.includes('EXACT COUNT') && f.includes('in the attached note'), f);
assert.strictEqual(C.facts('Tell me a joke', [{ title: 'x', text: 'alpha' }]), '');
const g = C.facts('how many times does alpha appear', [{ title: 'A', text: 'alpha alpha' }, { title: 'B', text: 'alpha' }, { title: 'C', text: 'none' }]);
assert.ok(g.includes('3 times in total') && g.includes('across 3 notes') && g.includes('A (2), B (1)') && !g.includes('C ('), g);
assert.ok(C.facts('how many times does zzz appear', [{ title: 'A', text: 'alpha' }]).includes('0 times'), 'zero is an exact answer too');
const t0 = Date.now(); C.count('alpha beta '.repeat(300000), 'alpha'); assert.ok(Date.now() - t0 < 2000, 'a 3 MB note is counted quickly');
