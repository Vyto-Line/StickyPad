from playwright.sync_api import sync_playwright
import os, sys
HERE=os.path.dirname(os.path.abspath(__file__)); STUB=open(os.path.join(HERE,'stub.js')).read(); fails=[]
def ok(c,m):
    print(('PASS ' if c else 'FAIL ')+m)
    if not c: fails.append(m)
ROOT='file://'+os.path.abspath(os.path.join(HERE,'..','..'))
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':330,'height':420}); errs=[]
    pg.on('pageerror',lambda e:errs.append(str(e))); pg.add_init_script(STUB)
    pg.goto(ROOT+'/note.html'); pg.wait_for_timeout(400)
    q=lambda: pg.evaluate("document.documentElement.classList.contains('quiet')")
    op=lambda: pg.evaluate("getComputedStyle(document.querySelector('header')).opacity")
    pg.wait_for_timeout(3600)
    ok(not q(),'off by default: the buttons never hide')
    pg.evaluate("__S.calls.length"); pg.evaluate("api.quietSet({mode:'away',delay:3})"); pg.mouse.move(165,200); pg.wait_for_timeout(300)
    pg.evaluate("document.documentElement.dispatchEvent(new MouseEvent('mouseleave'))"); pg.wait_for_timeout(3900)
    ok(q(),'mouse away and idle: hidden'); pg.wait_for_timeout(1200); ok(float(op())<0.05,'the title bar is invisible')
    pg.mouse.move(100,100); pg.wait_for_timeout(200); ok(not q(),'moving the mouse brings it back')
    pg.evaluate("document.documentElement.dispatchEvent(new MouseEvent('mouseleave'))"); pg.wait_for_timeout(3900); ok(q(),'hidden again')
    pg.keyboard.press('a'); pg.wait_for_timeout(100); ok(not q(),'typing brings it back')
    pg.evaluate("document.documentElement.dispatchEvent(new MouseEvent('mouseleave'))"); pg.wait_for_timeout(1500); pg.keyboard.press('b'); pg.wait_for_timeout(2000); ok(not q(),'typing resets the wait')
    pg.wait_for_timeout(2200); ok(q(),'then hides after the delay')
    pg.keyboard.press('b'); pg.click('#cfg'); pg.evaluate("document.documentElement.dispatchEvent(new MouseEvent('mouseleave'))"); pg.wait_for_timeout(4200)
    ok(not q(),'an open panel keeps the buttons visible')
    pg.click('#cfg'); pg.evaluate("window.__ACCESS={sr:true}"); pg.evaluate("api.accessSet({sr:true})"); pg.evaluate("document.documentElement.dispatchEvent(new MouseEvent('mouseleave'))"); pg.wait_for_timeout(4200)
    ok(not q(),'screen reader mode keeps the buttons visible')
    pg.evaluate("api.accessSet({sr:false})"); pg.wait_for_timeout(1200); ok(q(),'and hides again when it is off')
    pg.evaluate("api.quietSet({mode:'off'})"); pg.wait_for_timeout(200); ok(not q(),'switching it off shows them at once')
    pg.evaluate("api.quietSet({mode:'blur',delay:3})"); pg.evaluate("window.dispatchEvent(new Event('blur'))"); pg.wait_for_timeout(3900)
    ok(q(),'blur mode: hidden when the note is not in use'); pg.evaluate("window.dispatchEvent(new Event('focus'))"); pg.wait_for_timeout(100); ok(not q(),'and back when it is focused')
    ok(not errs,'no errors %s'%errs)
    pg2=b.new_page(viewport={'width':900,'height':700}); pg2.add_init_script(STUB); pg2.on('pageerror',lambda e:errs.append(str(e)))
    pg2.goto(ROOT+'/settings.html#notes'); pg2.wait_for_timeout(400)
    pg2.evaluate("document.querySelector('[data-cat=notes]').click()")
    ok(pg2.evaluate("document.querySelector('#quietMode').value")=='off','settings: Never by default')
    ok(pg2.evaluate("document.querySelector('#quietDelay').disabled"),'settings: delay disabled while off')
    pg2.select_option('#quietMode','both'); pg2.wait_for_timeout(300); pg2.select_option('#quietDelay','30'); pg2.wait_for_timeout(300)
    ok(pg2.evaluate("window.__QUIET.mode")=='both' and pg2.evaluate("window.__QUIET.delay")==30,'settings: choices are saved')
    ok(not pg2.evaluate("document.querySelector('#quietDelay').disabled"),'settings: delay enabled')
    ok(not errs,'no errors %s'%errs); b.close()
print('FAILS:',fails); sys.exit(1 if fails else 0)
