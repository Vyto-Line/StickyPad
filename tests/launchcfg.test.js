'use strict';
const assert = require('assert'), fs = require('fs'), os = require('os'), path = require('path');
const L = require('../launchcfg');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-launch-'));
assert.deepStrictEqual(L.read(dir), { lowMemory: true }, 'low memory mode is on by default');
L.write(dir, { lowMemory: false }); assert.deepStrictEqual(L.read(dir), { lowMemory: false });
L.write(dir, { lowMemory: true }); assert.deepStrictEqual(L.read(dir), { lowMemory: true });
fs.writeFileSync(path.join(dir, 'launch.json'), '{broken'); assert.deepStrictEqual(L.read(dir), { lowMemory: true }, 'a damaged file never stops the app from starting');
fs.writeFileSync(path.join(dir, 'launch.json'), '{"lowMemory":"yes"}'); assert.strictEqual(L.read(dir).lowMemory, true);
const on = L.plan({ lowMemory: true }), off = L.plan({ lowMemory: false });
assert.strictEqual(on.disableGpu, true); assert.strictEqual(off.disableGpu, false);
const feat = p => p.switches.find(s => s[0] === 'disable-features')[1].split(',');
assert.ok(feat(on).includes('CalculateNativeWinOcclusion') && feat(on).includes('MediaRouter')); assert.deepStrictEqual(feat(off), ['CalculateNativeWinOcclusion']);
assert.ok(on.switches.some(s => s[0] === 'js-flags' && /optimize-for-size/.test(s[1]))); assert.ok(!off.switches.some(s => s[0] === 'js-flags'));
assert.strictEqual(on.switches.filter(s => s[0] === 'disable-features').length, 1, 'disable-features is given once (a second one would override the first)');
fs.rmSync(dir, { recursive: true, force: true });
console.log('launchcfg ok');
