'use strict';
const assert = require('assert');
const Q = require('../quiet');
assert.deepStrictEqual(Q.clean(null), { mode: 'off', delay: 10 });
assert.deepStrictEqual(Q.clean({ mode: 'away', delay: 30 }), { mode: 'away', delay: 30 });
assert.deepStrictEqual(Q.clean({ mode: 'x', delay: 4 }), { mode: 'off', delay: 10 });
const base = { mode: 'away', delay: 3, now: 100000, over: false, lastMove: 100000, lastKey: 100000, focused: true, blurredAt: 0, hold: false };
const d = o => Q.decide({ ...base, ...o });
assert.strictEqual(d({ mode: 'off', now: 999999 }), false, 'off never hides');
assert.strictEqual(d({}), false, 'just moved: visible');
assert.strictEqual(d({ now: 102999 }), false, 'before the delay: visible');
assert.strictEqual(d({ now: 103000 }), true, 'mouse away and no typing for the delay: hidden');
assert.strictEqual(d({ now: 103000, over: true }), false, 'mouse over the note: visible');
assert.strictEqual(d({ now: 103000, lastKey: 102000 }), false, 'typed recently: visible');
assert.strictEqual(d({ now: 110000, hold: true }), false, 'an open panel keeps it visible');
assert.strictEqual(d({ mode: 'blur', now: 103000, focused: true, blurredAt: 0 }), false, 'blur mode: a focused note stays visible');
assert.strictEqual(d({ mode: 'blur', now: 103000, focused: false, blurredAt: 100000 }), true, 'blur mode: not in use for the delay');
assert.strictEqual(d({ mode: 'blur', now: 101000, focused: false, blurredAt: 100000 }), false, 'blur mode: not yet');
assert.strictEqual(d({ mode: 'both', now: 103000 }), true, 'both: away is enough');
assert.strictEqual(d({ mode: 'both', now: 103000, over: true, focused: false, blurredAt: 90000 }), true, 'both: blurred is enough');
assert.strictEqual(d({ mode: 'both', now: 103000, over: true }), false, 'both: neither');
console.log('quiet ok');
