// Prepares the screens for the Tauri build: copies the HTML/CSS/JS into src-tauri/ui, adds the small bridge that gives
// the pages the same `window.api` Electron's preload.js gives them, and allows Tauri's IPC in each page's CSP.
// The bridge is generated from preload.js, so the two can never drift apart.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), out = path.join(root, 'src-tauri', 'ui');

const preload = fs.readFileSync(path.join(root, 'preload.js'), 'utf8');
const calls = {}, events = {};
for (const m of preload.matchAll(/(\w+):\s*call\('([^']+)'\)/g)) calls[m[1]] = m[2];
for (const m of preload.matchAll(/(\w+):\s*cb\s*=>\s*ipcRenderer\.on\('([^']+)'/g)) events[m[1]] = m[2];
if (!Object.keys(calls).length) throw new Error('No api calls found in preload.js');

const shim = `// Generated by scripts/prep-tauri.js: gives the pages the same window.api as Electron's preload.js.
(function () {
  const T = window.__TAURI__;
  const CALLS = ${JSON.stringify(calls, null, 2)};
  const EVENTS = ${JSON.stringify(events, null, 2)};
  const api = {};
  Object.keys(CALLS).forEach(k => { api[k] = (...args) => T.core.invoke('ipc', { channel: CALLS[k], args }); });
  Object.keys(EVENTS).forEach(k => { api[k] = cb => { T.event.listen(EVENTS[k], e => cb(e.payload)); }; });
  window.api = api;
  // frameless windows: Tauri drags windows by elements marked with data-tauri-drag-region
  document.addEventListener('DOMContentLoaded', () => {
    document.querySelectorAll('header, .grip, .dragfill, .brand').forEach(el => el.setAttribute('data-tauri-drag-region', ''));
  });
})();
`;

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const CSP = "default-src 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src ipc: http://ipc.localhost";
const files = fs.readdirSync(root).filter(f => /\.(html|css)$/.test(f)).concat(['themes.js', 'reminders.js', 'ollamaui.js', 'note.js', 'all.js', 'chat.js', 'settings.js', 'splash.js', 'icon.png', 'tray.png']);
let pages = 0;
for (const f of files) {
  const src = path.join(root, f); if (!fs.existsSync(src)) continue;
  if (f.endsWith('.html')) {
    let h = fs.readFileSync(src, 'utf8');
    h = h.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>/i, `<meta http-equiv="Content-Security-Policy" content="${CSP}">`);
    h = h.replace(/<script /, '<script src="tauri-shim.js"></script>\n<script ');
    fs.writeFileSync(path.join(out, f), h); pages++;
  } else fs.copyFileSync(src, path.join(out, f));
}
fs.writeFileSync(path.join(out, 'tauri-shim.js'), shim);
console.log(`Prepared ${pages} pages and ${Object.keys(calls).length} api calls in src-tauri/ui`);
